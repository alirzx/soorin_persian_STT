"""Stable, low-cardinality Prometheus metrics: never label with audio or user data."""
from prometheus_client import Counter, Gauge, Histogram

REQUESTS = Counter("stt_requests_total", "Completed batch transcription requests", ["status"])
AUDIO_SECONDS = Counter("stt_audio_seconds_total", "Batch audio received in seconds")
INFERENCE = Histogram("stt_inference_seconds", "Batch inference duration in seconds")
RTF = Histogram("stt_realtime_factor", "Batch real-time factor")
ACTIVE = Gauge("stt_active_streams", "Current live streaming sessions")
MODEL_LOADED = Gauge("stt_model_loaded", "Loaded and warmed model")
MODEL_LOAD = Histogram("stt_model_load_seconds", "Model startup duration")
PARTIAL = Histogram("stt_time_to_first_partial_seconds", "First streaming hypothesis latency")
FINAL = Histogram("stt_finalization_latency_seconds", "Streaming finalization duration")
STREAM_ERRORS = Counter("stt_stream_errors_total", "Streaming errors", ["code"])
STREAM_SESSIONS = Counter("stt_stream_sessions_total", "Finished streaming sessions", ["outcome"])
STREAM_AUDIO = Counter("stt_stream_audio_seconds_total", "Streaming audio received in seconds")
STREAM_INFERENCE = Histogram("stt_stream_inference_seconds", "Streaming decoder calls", ["phase"])
STREAM_RTF = Histogram("stt_stream_realtime_factor", "Streaming segment realtime factor")
STREAM_SEGMENTS = Counter("stt_stream_segments_total", "Committed speech segments")
STREAM_QUEUE_DEPTH = Histogram("stt_stream_queue_frames", "Frames waiting during WS processing", buckets=(0,1,2,4,8,16,32,64,128,256,512,float("inf")))
STREAM_OVERFLOW = Counter("stt_stream_queue_overflow_total", "Dropped sessions due to queue backpressure")
CAPACITY_WAIT = Histogram("stt_inference_wait_seconds", "Time waiting for an inference slot")
INFERENCE_IN_FLIGHT = Gauge("stt_native_inference_in_flight", "Native inference threads still running")
